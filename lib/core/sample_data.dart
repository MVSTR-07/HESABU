String _fixtureMoney(int? cents) => cents == null
    ? '-'
    : '${cents < 0 ? '-' : ''}${cents.abs() ~/ 100}.${(cents.abs() % 100).toString().padLeft(2, '0')}';
String fixtureDate(DateTime at) {
  final k = at.toUtc().add(const Duration(hours: 3));
  String two(int v) => v.toString().padLeft(2, '0');
  return '${two(k.day)}/${two(k.month)}/${k.year} ${two(k.hour)}:${two(k.minute)}:${two(k.second)}';
}

/// CSV and PDF are generated from the same deterministic fixture rows.
Uint8List generateSampleMpesaCsv() {
  String quote(String value) => '"${value.replaceAll('"', '""')}"';
  final lines = <String>[
    'Receipt No.,Completion Time,Details,Transaction Status,Paid In,Withdrawn,Balance',
  ];
  for (final tx in generateSampleMpesaTransactions()) {
    lines.add(
      [
        tx.receipt,
        fixtureDate(tx.at),
        tx.details,
        'Completed',
        _fixtureMoney(tx.paidIn),
        _fixtureMoney(tx.withdrawn),
        _fixtureMoney(tx.balance),
      ].map(quote).join(','),
    );
  }
  return Uint8List.fromList(utf8.encode('${lines.join('\r\n')}\r\n'));
}

